import type { Field, Schema } from '@frictionless-ts/metadata'
import type { JSONSchema7, JSONSchema7Definition, JSONSchema7TypeName } from 'json-schema'
import type { JSONSchema } from 'json-schema-to-typescript'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { convertSchemaToJsonSchema } from '@frictionless-ts/metadata'
import { compile } from 'json-schema-to-typescript'

const CONTRACT_SCHEMA = new URL('../../contract/schema.json', import.meta.url)
const OUTPUT_DIR = new URL('../src/generated/', import.meta.url)
const FORMATS_KNOWN_TO_JSON_SCHEMA = new Set(['email', 'uri', 'uuid'])

await main()

async function main(): Promise<void> {
  const tableSchema: Schema = JSON.parse(readFileSync(CONTRACT_SCHEMA, 'utf8'))
  const recordSchema = toRecordSchema(tableSchema)

  mkdirSync(OUTPUT_DIR, { recursive: true })
  writeGeneratedFile('record.schema.json', `${JSON.stringify(recordSchema, null, 2)}\n`)
  writeGeneratedFile('record.ts', await compile(recordSchema as JSONSchema, 'RegistryRecord', {
    bannerComment: '// Generated by scripts/generate.ts from contract/schema.json',
  }))
}

function toRecordSchema(tableSchema: Schema): JSONSchema7 {
  // json-schema-to-typescript names a type after its title.
  const { title, ...converted } = convertSchemaToJsonSchema(tableSchema)
  const properties = Object.fromEntries(
    tableSchema.fields.map(field => [field.name, toRecordProperty(field, converted.properties?.[field.name])]),
  )

  // A row of a JSON table contains every field of the schema, and no other.
  return {
    ...converted,
    properties,
    required: Object.keys(properties),
    additionalProperties: false,
  }
}

function toRecordProperty(field: Field, converted: JSONSchema7Definition | undefined): JSONSchema7 {
  if (typeof converted !== 'object') {
    throw new TypeError(`The converter returns no property for the field ${field.name}`)
  }
  const property = { ...converted }

  // The converter omits the format of string fields.
  if (field.type === 'string' && field.format && FORMATS_KNOWN_TO_JSON_SCHEMA.has(field.format)) {
    property.format = field.format
  }
  // In Table Schema, an empty cell is null, and a field accepts null unless it is required.
  if (!field.constraints?.required) {
    property.type = [converted.type as JSONSchema7TypeName, 'null']
  }

  return property
}

function writeGeneratedFile(name: string, content: string): void {
  writeFileSync(new URL(name, OUTPUT_DIR), content)
}
