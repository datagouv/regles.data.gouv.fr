import type { JSONSchema } from 'json-schema-to-typescript'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { compile } from 'json-schema-to-typescript'

const CONTRACT_SCHEMA = new URL('../../contract/schema.json', import.meta.url)
const OUTPUT_DIR = new URL('../src/generated/', import.meta.url)
const RECORD_TYPE = 'RegistryRecord'
const BANNER = '// Generated by scripts/generate.ts from contract/schema.json'

await main()

async function main(): Promise<void> {
  const contractSchema: JSONSchema = JSON.parse(readFileSync(CONTRACT_SCHEMA, 'utf8'))
  const { version, 'x-unique-fields': uniqueFields, ...recordSchema } = contractSchema

  mkdirSync(OUTPUT_DIR, { recursive: true })
  writeGeneratedFile('record.schema.json', `${JSON.stringify(recordSchema, null, 2)}\n`)
  // json-schema-to-typescript names a type after its title.
  writeGeneratedFile('record.ts', await compile({ ...recordSchema, title: RECORD_TYPE }, RECORD_TYPE, {
    bannerComment: BANNER,
  }))
  writeGeneratedFile('schema-version.ts', `${BANNER}\n\nexport const SCHEMA_VERSION = ${JSON.stringify(toSchemaVersion(version))}\n`)
  writeGeneratedFile('unique-fields.ts', `${BANNER}\n\nimport type { ${RECORD_TYPE} } from './record.ts'\n\nexport const UNIQUE_FIELDS: (keyof ${RECORD_TYPE})[] = ${JSON.stringify(toUniqueFields(uniqueFields))}\n`)
}

function toSchemaVersion(version: unknown): string {
  if (typeof version !== 'string') {
    throw new TypeError('The contract schema declares no version')
  }
  return version
}

function toUniqueFields(uniqueFields: unknown): string[] {
  if (!Array.isArray(uniqueFields)) {
    throw new TypeError('The contract schema declares no unique fields')
  }
  return uniqueFields
}

function writeGeneratedFile(name: string, content: string): void {
  writeFileSync(new URL(name, OUTPUT_DIR), content)
}
